# 这个练习的重点不是"会用方法"，而是亲眼验证一件事：
#   ★ 字符串方法不会改变原来的字符串 ★
#
# 要求：按顺序完成下面 5 步，每步都要 print
#
#   1. 打印 raw.strip() 的结果
#   2. 打印 raw 本身        ← 关键：看它变了没有
#   3. 把 raw.strip() 的结果赋给新变量 clean，打印 clean
#   4. 打印 clean 的长度（用 len）
#   5. 打印 clean 的大写形式
#
# 预期输出（方括号是标记，不是输出内容）：
#   [1] Python 数据分析
#   [2] ␣␣␣Python 数据分析␣␣      ← raw 原样：前面 3 个空格、后面 2 个空格都还在
#   [3] Python 数据分析
#   [4] 11
#   [5] PYTHON 数据分析
#
# ␣ 表示空格。注意第 [2] 行 —— raw 完全没被改变。
# 如果你第 [2] 行输出的是不带空格的「Python 数据分析」，说明哪里写错了。
# （提示：strip() 返回新字符串，不会修改 raw 本身）
#
# 运行：python v2_text.py
# ------------------------------------------------------------------

raw = "   Python 数据分析  "
raw.strip()
print(raw.strip())
print(raw)
clean = raw.strip()
print(clean)
a = len(clean)
print(a)
print(clean.upper())
