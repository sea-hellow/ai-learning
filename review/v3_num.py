# 复习 · 变体练习 3／6：秒数换算成「天 小时 分 秒」（数字运算）
# ------------------------------------------------------------------
# 这是第 3 周 task3 的升级版：那次只换算到「小时」，这次多了「天」这一层。
#
# 要求：把 98765 秒换算成「几天几小时几分几秒」，输出一行
#
# 提示（照着这个思路算）：
#   day    = seconds // 86400            # 1 天 = 86400 秒
#   rest   = seconds %  86400            # 剩下多少秒
#   hour   = rest // 3600                # 1 小时 = 3600 秒
#   rest   = rest %  3600                # 再剩下多少秒
#   minute = rest // 60
#   second = rest %  60
#
# 然后用 f-string 输出。
#
# 预期输出：
#   98765 秒 = 1 天 3 小时 26 分 5 秒
#
# 自查方法：1×86400 + 3×3600 + 26×60 + 5 = 98765，对上了就说明算对了。
#
# 运行：python v3_num.py
# ------------------------------------------------------------------

seconds=98765
day=seconds//86400
rest=seconds%86400
hour=rest//3600
rest=rest%3600
minute=rest//60
rest=rest%60
second=rest%60
print(f"{seconds}秒 = {day}天{hour}小时{minute}分钟{second}秒")