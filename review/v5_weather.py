# 这是第 4 周 task2（成绩四档）的升级版：这次是气温五档，场景不同。
#
# 要求：给定气温 t，按下面规则打印等级
#
#   t >= 35          -> 酷热
#   30 <= t < 35     -> 炎热
#   20 <= t < 30     -> 舒适
#   10 <= t < 20     -> 微凉
#   t < 10           -> 寒冷
#
# 提示：
#   - 用 if / elif / else，缩进 4 个空格
#   - ★ 你不需要写 "30 <= t and t < 35" 这种组合条件 ★
#     想一想为什么：能走到那个 elif，说明前面的条件已经没命中，
#     那么此时 t 的范围其实已经被限定了。回顾第 1 轮串讲第 7.2 节。
#
# 验收（把 t 依次改成这些值，看输出对不对）：
#   t = 40  -> 酷热
#   t = 33  -> 炎热
#   t = 28  -> 舒适
#   t = 15  -> 微凉
#   t = 5   -> 寒冷
#
# 特别注意边界值：t = 35、30、20、10 各应该走哪一档？
#
# 运行：python v5_weather.py
# ------------------------------------------------------------------

t=28
if t>=35:
    print("酷热")
elif t>=30:
    print("炎热")
elif t>=20:
    print("舒适")
elif t>=10:
    print("微凉")
else:
    print("寒冷")